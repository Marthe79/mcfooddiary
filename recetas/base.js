window.MC_RECETAS = [];

/* Añade ingredientes nuevos sin pisar los que ya existen (el primero que se define, gana). */
window.MC_ADD_ING = function (obj) {
  for (const k in obj) if (!(k in window.MC_INGREDIENTES)) window.MC_INGREDIENTES[k] = obj[k];
};

/* Registra las recetas de una cocina. */
window.MC_ADD = function (co, recetas) {
  for (const r of recetas) window.MC_RECETAS.push(Object.assign({ co: co }, r));
};
